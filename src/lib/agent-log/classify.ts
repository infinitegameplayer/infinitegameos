// One kind per request, in this precedence (Agent Visit Log plan, Locked
// Architecture): declared, declared_other, provider_range, likely_human,
// unknown. agent_name is only ever a value from the generated name list,
// never header text. `ours` is never set here; the reader's join sets it.

import ranges from './ranges.json'
import { compileCidr, inRanges, parseIp, type CompiledRange, type ParsedIp } from './ip'

export type Kind = 'declared' | 'declared_other' | 'provider_range' | 'likely_human' | 'unknown'
// no_address: the request carried no readable address, so nothing was checked
// (never read as an impostor).
export type RangeVerdict = 'in_range' | 'out_of_range' | 'no_complete_list' | 'no_address'

export type ClassifyInput = {
  userAgent: string | null
  ip: string | null
  secFetchDest: string | null
  secFetchMode: string | null
  signatureAgent: string | null
  signatureInput: string | null
}

export type Classification = {
  kind: Kind
  agent_name: string | null
  signature_present: boolean
  range_provider: string | null
  range_verdict: RangeVerdict
}

type List = { id: string; agents: string[]; status: string; compiled: CompiledRange[] }

// Compiled once per instance. ranges.json is generated by
// Council Chamber/scripts/agent-ranges-refresh.mjs and bundled at deploy.
const LISTS: List[] = ranges.lists.map((l) => ({
  id: l.id,
  agents: l.agents,
  status: l.status,
  compiled: [...l.ipv4, ...l.ipv6].map(compileCidr).filter((r): r is CompiledRange => r !== null),
}))

// The file already sorts longest first, so Applebot-Extended precedes Applebot;
// robots-only tokens (ua_token false) never arrive as a user agent.
const NAMES = ranges.names
  .filter((n) => n.ua_token)
  .map((n) => ({ name: n.name, lower: n.name.toLowerCase() }))
  .sort((a, b) => b.lower.length - a.lower.length)

const GENERIC =
  /bot\b|bot\/|crawler|crawl|spider|slurp|curl\/|wget\/|python|node-fetch|\bnode\/|undici|axios\/|okhttp|go-http-client|java\/|libwww|scrapy|httpx|aiohttp|headless|phantomjs|puppeteer|playwright|selenium/i

const BROWSER = /^Mozilla\/5\.0 .*(Chrome|Firefox|Safari|Edg)\//

export const RANGES_DATE: string = ranges.generated.slice(0, 10)

function declaredName(ua: string): string | null {
  const lower = ua.toLowerCase()
  for (const n of NAMES) if (lower.includes(n.lower)) return n.name
  return null
}

function firstListContaining(ip: ParsedIp | null, lists: List[]): List | null {
  if (!ip) return null
  for (const l of lists) if (inRanges(ip, l.compiled)) return l
  return null
}

export function classify(input: ClassifyInput): Classification {
  const ua = input.userAgent ?? ''
  const ip = parseIp(input.ip)
  const signature_present = Boolean(input.signatureAgent || input.signatureInput)

  const name = ua ? declaredName(ua) : null
  if (name) {
    const own = LISTS.filter((l) => l.agents.includes(name) && l.status !== 'none')
    const hit = firstListContaining(ip, own)
    let range_verdict: RangeVerdict
    if (!ip) range_verdict = 'no_address'
    else if (hit) range_verdict = 'in_range'
    else if (own.some((l) => l.status === 'complete')) range_verdict = 'out_of_range'
    else range_verdict = 'no_complete_list'
    return { kind: 'declared', agent_name: name, signature_present, range_provider: hit?.id ?? null, range_verdict }
  }

  const anyHit = firstListContaining(ip, LISTS)
  const range = {
    range_provider: anyHit?.id ?? null,
    range_verdict: (!ip ? 'no_address' : anyHit ? 'in_range' : 'out_of_range') as RangeVerdict,
  }

  // A browser-shaped user agent names its device in its first parentheses, and
  // some phone models end in "bot" (CUBOT). The generic test skips that part
  // for a browser shape; a bot that names itself later in the string is caught.
  const genericText = BROWSER.test(ua) ? ua.replace(/\([^)]*\)/, '') : ua
  if (ua && GENERIC.test(genericText)) return { kind: 'declared_other', agent_name: null, signature_present, ...range }
  if (anyHit) return { kind: 'provider_range', agent_name: null, signature_present, ...range }
  if (BROWSER.test(ua) && (input.secFetchDest || input.secFetchMode)) {
    return { kind: 'likely_human', agent_name: null, signature_present, ...range }
  }
  return { kind: 'unknown', agent_name: null, signature_present, ...range }
}
